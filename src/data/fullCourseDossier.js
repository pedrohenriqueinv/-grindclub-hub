export function findSpecificActionCard(query) {
  const q = query.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  const wantsTutorial = q.includes('tutorial') || q.includes('passo a passo') || q.includes('prints') || q.includes('guia') || q.includes('como criar');
  if (!wantsTutorial) return null;

  let bestTopic = null;
  let highestScore = 0;

  for (const topic of LOCAL_DOSSIER_TOPICS) {
    let score = 0;
    for (const kw of topic.keywords) {
      const cleanKw = kw.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
      if (q.includes(cleanKw)) score += 8;
    }
    if (score > highestScore) {
      highestScore = score;
      bestTopic = topic;
    }
  }

  if (bestTopic && highestScore >= 8) {
    return {
      card: {
        title: bestTopic.title,
        steps: bestTopic.steps,
        alert: bestTopic.alert,
        actions: [
          bestTopic.action,
          bestTopic.prints && bestTopic.prints.length > 0 ? { label: 'Ver Prints Oficiais', actionType: 'prints', target: bestTopic.id } : null
        ].filter(Boolean)
      },
      prints: bestTopic.prints || []
    };
  }

  return null;
}

export async function askVykAiHybrid(userMessage, conversationHistory = [], accountContext = null) {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 12000);

    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ 
        message: userMessage,
        history: conversationHistory,
        accountContext: accountContext 
      }),
      signal: controller.signal
    });

    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (data.text) {
        // Anexa card APENAS se o usuário tiver pedido um tutorial ou prints específicos
        const specificMatch = findSpecificActionCard(userMessage);

        return {
          source: 'grindclub-ai',
          text: data.text,
          card: specificMatch?.card || null,
          prints: specificMatch?.prints || []
        };
      }
    }
  } catch (err) {
    console.warn('Vyk AI: Utilizando motor neural local do Dossiê:', err);
  }

  const localResult = searchLocalDossier(userMessage);
  return {
    source: 'grindclub-dossier',
    text: localResult.text,
    card: localResult.card,
    prints: localResult.prints
  };
}
